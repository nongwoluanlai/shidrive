export type TranslationParams = Record<string, string | number>;

export function localeTag(): "zh-CN" | "en-US" {
  return app.locale === "en" ? "en-US" : "zh-CN";
}

export function t(zh: string, params: TranslationParams = {}): string {
  let text = zh;
  if (app.locale === "en") {
    // Preserve leading/trailing layout whitespace and decorative menu icons.
    const core = zh.trim().replace(/\s+/g, " ");
    const decorated = core.match(/^([^\p{L}\p{N}]+\s+)(.+)$/u);
    const translated = en[zh] ?? en[core] ?? (decorated && en[decorated[2]] !== undefined ? decorated[1] + en[decorated[2]] : undefined);
    if (translated !== undefined) {
      text = en[zh] !== undefined ? translated : zh.match(/^\s*/)! [0] + translated + zh.match(/\s*$/)! [0];
    }
  }
  return text.replace(/\{([\w]+)\}/g, (token, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : token,
  );
}
